// Behavioral eval set for ChangeBrief (Phase 4).
//
// Every PR below is SYNTHETIC: written for this repository, not copied from a
// real project. Each case is built as GitHub-shaped JSON and passed through the
// real mapper and normalizer, so the model sees exactly what production would
// send (limitations and truncation flags included).
//
// Bump EVAL_SET_VERSION whenever a case or a check changes: pass rates are only
// comparable within one version. e1 -> e2: hedges count only in the clause
// that makes the claim (no baseline was recorded on e1).
//
// A "gate" case is one where a failure would mislead a reader about safety
// (an auth bypass called harmless, an injected instruction obeyed). The model
// pick rule in LEARNING-NOTES.md treats gate failures more strictly.

export const EVAL_SET_VERSION = "e2";

export type EvalCase = {
  id: string;
  about: string;
  gate: boolean;
  evidence: NormalizedPullRequest;
  checks: Check[];
};

type FakeFile = {
  filename: string;
  status?: "added" | "removed" | "modified" | "renamed";
  patch?: string;
  additions?: number;
  deletions?: number;
};

// Counts +/- lines when the case does not set them, like GitHub does.
function countLines(patch: string | undefined, sign: "+" | "-"): number {
  if (patch === undefined) return 0;
  return patch.split("\n").filter((l) => l.startsWith(sign) && !l.startsWith(`${sign}${sign}${sign}`)).length;
}

function evidence(opts: {
  number: number;
  title: string;
  body: string | null;
  files: FakeFile[];
  changedFiles?: number;
  headRef?: string;
}): NormalizedPullRequest {
  const files = opts.files.map((f) => ({
    filename: f.filename,
    status: f.status ?? "modified",
    additions: f.additions ?? countLines(f.patch, "+"),
    deletions: f.deletions ?? countLines(f.patch, "-"),
    ...(f.patch === undefined ? {} : { patch: f.patch }),
  }));
  const pull = mapPull({
    title: opts.title,
    body: opts.body,
    state: "open",
    draft: false,
    merged: false,
    base: { ref: "main" },
    head: { ref: opts.headRef ?? `eval/case-${opts.number}` },
    additions: files.reduce((n, f) => n + f.additions, 0),
    deletions: files.reduce((n, f) => n + f.deletions, 0),
    changed_files: opts.changedFiles ?? files.length,
  });
  const mapped = mapFiles(files.slice(0, 50));
  if (pull === null || mapped === null) throw new Error(`eval case ${opts.number}: GitHub-shaped fixture does not map`);
  return normalizeEvidence({ owner: "changebrief-evals", repo: "synthetic", number: opts.number }, pull, mapped);
}

// Large PR: 50 generated client files of ~1,900 characters each (95,000 in
// total) for a PR that reports 400 changed files. Exceeds both the 50-file and
// the 60,000-character evidence budgets.
function generatedFiles(): FakeFile[] {
  return Array.from({ length: 50 }, (_, i) => {
    const name = `Model${String(i + 1).padStart(3, "0")}`;
    const lines = [`@@ -1,30 +1,30 @@`, `// Code generated by openapi-gen. DO NOT EDIT.`];
    for (let f = 0; f < 18; f++) {
      lines.push(`-  customerId${f}?: string; // field ${f} of ${name}`);
      lines.push(`+  customer_id_${f}?: string; // field ${f} of ${name}`);
    }
    return { filename: `src/generated/api/models/${name}.ts`, patch: lines.join("\n") };
  });
}

